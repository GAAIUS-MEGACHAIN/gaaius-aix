import React, { FC, ReactNode } from 'react';
import styles from './Spinner.module.css';

interface SpinnerProps {
  children?: ReactNode;
  className?: string;
  disabled?: boolean;
  variant?: 'primary' | 'secondary' | 'danger';
  size?: 'sm' | 'md' | 'lg';
  onClick?: () => void;
}

/**
 * Spinner Component
 * A reusable Spinner component for the application
 * 
 * @param SpinnerProps - Component props
 * @returns Rendered Spinner component
 */
const Spinner: FC<SpinnerProps> = ({
  children,
  className = '',
  disabled = false,
  variant = 'primary',
  size = 'md',
  onClick,
}) => {
  // Determine variant classes
  const variantClass = `$Spinner--${variant}`;
  const sizeClass = `$Spinner--${size}`;
  
  // Combine all classes
  const finalClassName = `${[
    styles.Spinner,
    styles[variantClass],
    styles[sizeClass],
    disabled && styles.disabled,
    className,
  ].join(' ')}`;
  
  // Handle click event
  const handleClick = () => {
    if (!disabled && onClick) {
      onClick();
    }
  };
  
  // Render component
  return (
    <button
      className={finalClassName}
      disabled={disabled}
      onClick={handleClick}
      role="button"
      aria-disabled={disabled}
    >
      {children}
    </button>
  );
};

Spinner.displayName = 'Spinner';

export default Spinner;

