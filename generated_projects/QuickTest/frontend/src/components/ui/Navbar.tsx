import React, { FC, ReactNode } from 'react';
import styles from './Navbar.module.css';

interface NavbarProps {
  children?: ReactNode;
  className?: string;
  disabled?: boolean;
  variant?: 'primary' | 'secondary' | 'danger';
  size?: 'sm' | 'md' | 'lg';
  onClick?: () => void;
}

/**
 * Navbar Component
 * A reusable Navbar component for the application
 * 
 * @param NavbarProps - Component props
 * @returns Rendered Navbar component
 */
const Navbar: FC<NavbarProps> = ({
  children,
  className = '',
  disabled = false,
  variant = 'primary',
  size = 'md',
  onClick,
}) => {
  // Determine variant classes
  const variantClass = `$Navbar--${variant}`;
  const sizeClass = `$Navbar--${size}`;
  
  // Combine all classes
  const finalClassName = `${[
    styles.Navbar,
    styles[variantClass],
    styles[sizeClass],
    disabled && styles.disabled,
    className,
  ].join(' ')}`;
  
  // Handle click event
  const handleClick = () => {
    if (!disabled && onClick) {
      onClick();
    }
  };
  
  // Render component
  return (
    <button
      className={finalClassName}
      disabled={disabled}
      onClick={handleClick}
      role="button"
      aria-disabled={disabled}
    >
      {children}
    </button>
  );
};

Navbar.displayName = 'Navbar';

export default Navbar;

