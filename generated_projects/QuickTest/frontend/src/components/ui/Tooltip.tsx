import React, { FC, ReactNode } from 'react';
import styles from './Tooltip.module.css';

interface TooltipProps {
  children?: ReactNode;
  className?: string;
  disabled?: boolean;
  variant?: 'primary' | 'secondary' | 'danger';
  size?: 'sm' | 'md' | 'lg';
  onClick?: () => void;
}

/**
 * Tooltip Component
 * A reusable Tooltip component for the application
 * 
 * @param TooltipProps - Component props
 * @returns Rendered Tooltip component
 */
const Tooltip: FC<TooltipProps> = ({
  children,
  className = '',
  disabled = false,
  variant = 'primary',
  size = 'md',
  onClick,
}) => {
  // Determine variant classes
  const variantClass = `$Tooltip--${variant}`;
  const sizeClass = `$Tooltip--${size}`;
  
  // Combine all classes
  const finalClassName = `${[
    styles.Tooltip,
    styles[variantClass],
    styles[sizeClass],
    disabled && styles.disabled,
    className,
  ].join(' ')}`;
  
  // Handle click event
  const handleClick = () => {
    if (!disabled && onClick) {
      onClick();
    }
  };
  
  // Render component
  return (
    <button
      className={finalClassName}
      disabled={disabled}
      onClick={handleClick}
      role="button"
      aria-disabled={disabled}
    >
      {children}
    </button>
  );
};

Tooltip.displayName = 'Tooltip';

export default Tooltip;

