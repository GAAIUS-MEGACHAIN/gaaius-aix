import React, { FC, ReactNode } from 'react';
import styles from './Badge.module.css';

interface BadgeProps {
  children?: ReactNode;
  className?: string;
  disabled?: boolean;
  variant?: 'primary' | 'secondary' | 'danger';
  size?: 'sm' | 'md' | 'lg';
  onClick?: () => void;
}

/**
 * Badge Component
 * A reusable Badge component for the application
 * 
 * @param BadgeProps - Component props
 * @returns Rendered Badge component
 */
const Badge: FC<BadgeProps> = ({
  children,
  className = '',
  disabled = false,
  variant = 'primary',
  size = 'md',
  onClick,
}) => {
  // Determine variant classes
  const variantClass = `$Badge--${variant}`;
  const sizeClass = `$Badge--${size}`;
  
  // Combine all classes
  const finalClassName = `${[
    styles.Badge,
    styles[variantClass],
    styles[sizeClass],
    disabled && styles.disabled,
    className,
  ].join(' ')}`;
  
  // Handle click event
  const handleClick = () => {
    if (!disabled && onClick) {
      onClick();
    }
  };
  
  // Render component
  return (
    <button
      className={finalClassName}
      disabled={disabled}
      onClick={handleClick}
      role="button"
      aria-disabled={disabled}
    >
      {children}
    </button>
  );
};

Badge.displayName = 'Badge';

export default Badge;

