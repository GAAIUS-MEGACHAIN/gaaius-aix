import React, { FC, ReactNode } from 'react';
import styles from './Dropdown.module.css';

interface DropdownProps {
  children?: ReactNode;
  className?: string;
  disabled?: boolean;
  variant?: 'primary' | 'secondary' | 'danger';
  size?: 'sm' | 'md' | 'lg';
  onClick?: () => void;
}

/**
 * Dropdown Component
 * A reusable Dropdown component for the application
 * 
 * @param DropdownProps - Component props
 * @returns Rendered Dropdown component
 */
const Dropdown: FC<DropdownProps> = ({
  children,
  className = '',
  disabled = false,
  variant = 'primary',
  size = 'md',
  onClick,
}) => {
  // Determine variant classes
  const variantClass = `$Dropdown--${variant}`;
  const sizeClass = `$Dropdown--${size}`;
  
  // Combine all classes
  const finalClassName = `${[
    styles.Dropdown,
    styles[variantClass],
    styles[sizeClass],
    disabled && styles.disabled,
    className,
  ].join(' ')}`;
  
  // Handle click event
  const handleClick = () => {
    if (!disabled && onClick) {
      onClick();
    }
  };
  
  // Render component
  return (
    <button
      className={finalClassName}
      disabled={disabled}
      onClick={handleClick}
      role="button"
      aria-disabled={disabled}
    >
      {children}
    </button>
  );
};

Dropdown.displayName = 'Dropdown';

export default Dropdown;

