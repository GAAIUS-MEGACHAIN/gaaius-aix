import React, { FC, ReactNode } from 'react';
import styles from './Button.module.css';

interface ButtonProps {
  children?: ReactNode;
  className?: string;
  disabled?: boolean;
  variant?: 'primary' | 'secondary' | 'danger';
  size?: 'sm' | 'md' | 'lg';
  onClick?: () => void;
}

/**
 * Button Component
 * A reusable Button component for the application
 * 
 * @param ButtonProps - Component props
 * @returns Rendered Button component
 */
const Button: FC<ButtonProps> = ({
  children,
  className = '',
  disabled = false,
  variant = 'primary',
  size = 'md',
  onClick,
}) => {
  // Determine variant classes
  const variantClass = `$Button--${variant}`;
  const sizeClass = `$Button--${size}`;
  
  // Combine all classes
  const finalClassName = `${[
    styles.Button,
    styles[variantClass],
    styles[sizeClass],
    disabled && styles.disabled,
    className,
  ].join(' ')}`;
  
  // Handle click event
  const handleClick = () => {
    if (!disabled && onClick) {
      onClick();
    }
  };
  
  // Render component
  return (
    <button
      className={finalClassName}
      disabled={disabled}
      onClick={handleClick}
      role="button"
      aria-disabled={disabled}
    >
      {children}
    </button>
  );
};

Button.displayName = 'Button';

export default Button;

