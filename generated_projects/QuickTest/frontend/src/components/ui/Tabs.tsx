import React, { FC, ReactNode } from 'react';
import styles from './Tabs.module.css';

interface TabsProps {
  children?: ReactNode;
  className?: string;
  disabled?: boolean;
  variant?: 'primary' | 'secondary' | 'danger';
  size?: 'sm' | 'md' | 'lg';
  onClick?: () => void;
}

/**
 * Tabs Component
 * A reusable Tabs component for the application
 * 
 * @param TabsProps - Component props
 * @returns Rendered Tabs component
 */
const Tabs: FC<TabsProps> = ({
  children,
  className = '',
  disabled = false,
  variant = 'primary',
  size = 'md',
  onClick,
}) => {
  // Determine variant classes
  const variantClass = `$Tabs--${variant}`;
  const sizeClass = `$Tabs--${size}`;
  
  // Combine all classes
  const finalClassName = `${[
    styles.Tabs,
    styles[variantClass],
    styles[sizeClass],
    disabled && styles.disabled,
    className,
  ].join(' ')}`;
  
  // Handle click event
  const handleClick = () => {
    if (!disabled && onClick) {
      onClick();
    }
  };
  
  // Render component
  return (
    <button
      className={finalClassName}
      disabled={disabled}
      onClick={handleClick}
      role="button"
      aria-disabled={disabled}
    >
      {children}
    </button>
  );
};

Tabs.displayName = 'Tabs';

export default Tabs;

