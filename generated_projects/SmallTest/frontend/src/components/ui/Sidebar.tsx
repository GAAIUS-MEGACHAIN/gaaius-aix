import React, { FC, ReactNode } from 'react';
import styles from './Sidebar.module.css';

interface SidebarProps {
  children?: ReactNode;
  className?: string;
  disabled?: boolean;
  variant?: 'primary' | 'secondary' | 'danger';
  size?: 'sm' | 'md' | 'lg';
  onClick?: () => void;
}

/**
 * Sidebar Component
 * A reusable Sidebar component for the application
 * 
 * @param SidebarProps - Component props
 * @returns Rendered Sidebar component
 */
const Sidebar: FC<SidebarProps> = ({
  children,
  className = '',
  disabled = false,
  variant = 'primary',
  size = 'md',
  onClick,
}) => {
  // Determine variant classes
  const variantClass = `$Sidebar--${variant}`;
  const sizeClass = `$Sidebar--${size}`;
  
  // Combine all classes
  const finalClassName = `${[
    styles.Sidebar,
    styles[variantClass],
    styles[sizeClass],
    disabled && styles.disabled,
    className,
  ].join(' ')}`;
  
  // Handle click event
  const handleClick = () => {
    if (!disabled && onClick) {
      onClick();
    }
  };
  
  // Render component
  return (
    <button
      className={finalClassName}
      disabled={disabled}
      onClick={handleClick}
      role="button"
      aria-disabled={disabled}
    >
      {children}
    </button>
  );
};

Sidebar.displayName = 'Sidebar';

export default Sidebar;

