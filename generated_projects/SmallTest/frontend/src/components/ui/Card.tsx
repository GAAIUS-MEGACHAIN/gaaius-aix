import React, { FC, ReactNode } from 'react';
import styles from './Card.module.css';

interface CardProps {
  children?: ReactNode;
  className?: string;
  disabled?: boolean;
  variant?: 'primary' | 'secondary' | 'danger';
  size?: 'sm' | 'md' | 'lg';
  onClick?: () => void;
}

/**
 * Card Component
 * A reusable Card component for the application
 * 
 * @param CardProps - Component props
 * @returns Rendered Card component
 */
const Card: FC<CardProps> = ({
  children,
  className = '',
  disabled = false,
  variant = 'primary',
  size = 'md',
  onClick,
}) => {
  // Determine variant classes
  const variantClass = `$Card--${variant}`;
  const sizeClass = `$Card--${size}`;
  
  // Combine all classes
  const finalClassName = `${[
    styles.Card,
    styles[variantClass],
    styles[sizeClass],
    disabled && styles.disabled,
    className,
  ].join(' ')}`;
  
  // Handle click event
  const handleClick = () => {
    if (!disabled && onClick) {
      onClick();
    }
  };
  
  // Render component
  return (
    <button
      className={finalClassName}
      disabled={disabled}
      onClick={handleClick}
      role="button"
      aria-disabled={disabled}
    >
      {children}
    </button>
  );
};

Card.displayName = 'Card';

export default Card;

