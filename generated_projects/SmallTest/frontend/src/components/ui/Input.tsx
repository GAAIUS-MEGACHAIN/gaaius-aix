import React, { FC, ReactNode } from 'react';
import styles from './Input.module.css';

interface InputProps {
  children?: ReactNode;
  className?: string;
  disabled?: boolean;
  variant?: 'primary' | 'secondary' | 'danger';
  size?: 'sm' | 'md' | 'lg';
  onClick?: () => void;
}

/**
 * Input Component
 * A reusable Input component for the application
 * 
 * @param InputProps - Component props
 * @returns Rendered Input component
 */
const Input: FC<InputProps> = ({
  children,
  className = '',
  disabled = false,
  variant = 'primary',
  size = 'md',
  onClick,
}) => {
  // Determine variant classes
  const variantClass = `$Input--${variant}`;
  const sizeClass = `$Input--${size}`;
  
  // Combine all classes
  const finalClassName = `${[
    styles.Input,
    styles[variantClass],
    styles[sizeClass],
    disabled && styles.disabled,
    className,
  ].join(' ')}`;
  
  // Handle click event
  const handleClick = () => {
    if (!disabled && onClick) {
      onClick();
    }
  };
  
  // Render component
  return (
    <button
      className={finalClassName}
      disabled={disabled}
      onClick={handleClick}
      role="button"
      aria-disabled={disabled}
    >
      {children}
    </button>
  );
};

Input.displayName = 'Input';

export default Input;

