import React, { FC, ReactNode } from 'react';
import styles from './Alert.module.css';

interface AlertProps {
  children?: ReactNode;
  className?: string;
  disabled?: boolean;
  variant?: 'primary' | 'secondary' | 'danger';
  size?: 'sm' | 'md' | 'lg';
  onClick?: () => void;
}

/**
 * Alert Component
 * A reusable Alert component for the application
 * 
 * @param AlertProps - Component props
 * @returns Rendered Alert component
 */
const Alert: FC<AlertProps> = ({
  children,
  className = '',
  disabled = false,
  variant = 'primary',
  size = 'md',
  onClick,
}) => {
  // Determine variant classes
  const variantClass = `$Alert--${variant}`;
  const sizeClass = `$Alert--${size}`;
  
  // Combine all classes
  const finalClassName = `${[
    styles.Alert,
    styles[variantClass],
    styles[sizeClass],
    disabled && styles.disabled,
    className,
  ].join(' ')}`;
  
  // Handle click event
  const handleClick = () => {
    if (!disabled && onClick) {
      onClick();
    }
  };
  
  // Render component
  return (
    <button
      className={finalClassName}
      disabled={disabled}
      onClick={handleClick}
      role="button"
      aria-disabled={disabled}
    >
      {children}
    </button>
  );
};

Alert.displayName = 'Alert';

export default Alert;

