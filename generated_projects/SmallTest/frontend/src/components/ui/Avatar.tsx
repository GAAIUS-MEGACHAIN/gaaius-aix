import React, { FC, ReactNode } from 'react';
import styles from './Avatar.module.css';

interface AvatarProps {
  children?: ReactNode;
  className?: string;
  disabled?: boolean;
  variant?: 'primary' | 'secondary' | 'danger';
  size?: 'sm' | 'md' | 'lg';
  onClick?: () => void;
}

/**
 * Avatar Component
 * A reusable Avatar component for the application
 * 
 * @param AvatarProps - Component props
 * @returns Rendered Avatar component
 */
const Avatar: FC<AvatarProps> = ({
  children,
  className = '',
  disabled = false,
  variant = 'primary',
  size = 'md',
  onClick,
}) => {
  // Determine variant classes
  const variantClass = `$Avatar--${variant}`;
  const sizeClass = `$Avatar--${size}`;
  
  // Combine all classes
  const finalClassName = `${[
    styles.Avatar,
    styles[variantClass],
    styles[sizeClass],
    disabled && styles.disabled,
    className,
  ].join(' ')}`;
  
  // Handle click event
  const handleClick = () => {
    if (!disabled && onClick) {
      onClick();
    }
  };
  
  // Render component
  return (
    <button
      className={finalClassName}
      disabled={disabled}
      onClick={handleClick}
      role="button"
      aria-disabled={disabled}
    >
      {children}
    </button>
  );
};

Avatar.displayName = 'Avatar';

export default Avatar;

