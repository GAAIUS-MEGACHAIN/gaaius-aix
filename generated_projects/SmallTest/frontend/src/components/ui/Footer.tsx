import React, { FC, ReactNode } from 'react';
import styles from './Footer.module.css';

interface FooterProps {
  children?: ReactNode;
  className?: string;
  disabled?: boolean;
  variant?: 'primary' | 'secondary' | 'danger';
  size?: 'sm' | 'md' | 'lg';
  onClick?: () => void;
}

/**
 * Footer Component
 * A reusable Footer component for the application
 * 
 * @param FooterProps - Component props
 * @returns Rendered Footer component
 */
const Footer: FC<FooterProps> = ({
  children,
  className = '',
  disabled = false,
  variant = 'primary',
  size = 'md',
  onClick,
}) => {
  // Determine variant classes
  const variantClass = `$Footer--${variant}`;
  const sizeClass = `$Footer--${size}`;
  
  // Combine all classes
  const finalClassName = `${[
    styles.Footer,
    styles[variantClass],
    styles[sizeClass],
    disabled && styles.disabled,
    className,
  ].join(' ')}`;
  
  // Handle click event
  const handleClick = () => {
    if (!disabled && onClick) {
      onClick();
    }
  };
  
  // Render component
  return (
    <button
      className={finalClassName}
      disabled={disabled}
      onClick={handleClick}
      role="button"
      aria-disabled={disabled}
    >
      {children}
    </button>
  );
};

Footer.displayName = 'Footer';

export default Footer;

