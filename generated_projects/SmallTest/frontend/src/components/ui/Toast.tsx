import React, { FC, ReactNode } from 'react';
import styles from './Toast.module.css';

interface ToastProps {
  children?: ReactNode;
  className?: string;
  disabled?: boolean;
  variant?: 'primary' | 'secondary' | 'danger';
  size?: 'sm' | 'md' | 'lg';
  onClick?: () => void;
}

/**
 * Toast Component
 * A reusable Toast component for the application
 * 
 * @param ToastProps - Component props
 * @returns Rendered Toast component
 */
const Toast: FC<ToastProps> = ({
  children,
  className = '',
  disabled = false,
  variant = 'primary',
  size = 'md',
  onClick,
}) => {
  // Determine variant classes
  const variantClass = `$Toast--${variant}`;
  const sizeClass = `$Toast--${size}`;
  
  // Combine all classes
  const finalClassName = `${[
    styles.Toast,
    styles[variantClass],
    styles[sizeClass],
    disabled && styles.disabled,
    className,
  ].join(' ')}`;
  
  // Handle click event
  const handleClick = () => {
    if (!disabled && onClick) {
      onClick();
    }
  };
  
  // Render component
  return (
    <button
      className={finalClassName}
      disabled={disabled}
      onClick={handleClick}
      role="button"
      aria-disabled={disabled}
    >
      {children}
    </button>
  );
};

Toast.displayName = 'Toast';

export default Toast;

