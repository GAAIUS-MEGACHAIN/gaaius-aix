import React, { FC, ReactNode } from 'react';
import styles from './Modal.module.css';

interface ModalProps {
  children?: ReactNode;
  className?: string;
  disabled?: boolean;
  variant?: 'primary' | 'secondary' | 'danger';
  size?: 'sm' | 'md' | 'lg';
  onClick?: () => void;
}

/**
 * Modal Component
 * A reusable Modal component for the application
 * 
 * @param ModalProps - Component props
 * @returns Rendered Modal component
 */
const Modal: FC<ModalProps> = ({
  children,
  className = '',
  disabled = false,
  variant = 'primary',
  size = 'md',
  onClick,
}) => {
  // Determine variant classes
  const variantClass = `$Modal--${variant}`;
  const sizeClass = `$Modal--${size}`;
  
  // Combine all classes
  const finalClassName = `${[
    styles.Modal,
    styles[variantClass],
    styles[sizeClass],
    disabled && styles.disabled,
    className,
  ].join(' ')}`;
  
  // Handle click event
  const handleClick = () => {
    if (!disabled && onClick) {
      onClick();
    }
  };
  
  // Render component
  return (
    <button
      className={finalClassName}
      disabled={disabled}
      onClick={handleClick}
      role="button"
      aria-disabled={disabled}
    >
      {children}
    </button>
  );
};

Modal.displayName = 'Modal';

export default Modal;

