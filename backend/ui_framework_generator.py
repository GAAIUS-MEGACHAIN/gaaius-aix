"""
UI FRAMEWORK GENERATOR
Support for: Shadcn/ui, Ant Design, Material-UI, Bootstrap, Chakra UI, Tailwind, Daisy UI
"""

import json
from typing import Dict, List, Optional, Any
from dataclasses import dataclass

@dataclass
class UIFrameworkConfig:
    """Configuration for UI framework setup"""
    project_id: str
    project_name: str
    framework: str  # "shadcn", "antd", "mui", "bootstrap", "chakra", "tailwind", "daisy"
    theme: str = "light"  # "light", "dark", "system"
    typescript: bool = True


class UIFrameworkGenerator:
    """Generates UI framework configurations and component libraries"""
    
    SUPPORTED_FRAMEWORKS = ["shadcn", "antd", "mui", "bootstrap", "chakra", "tailwind", "daisy"]
    
    def generate(self, config: UIFrameworkConfig) -> Dict[str, str]:
        """Generate UI framework setup"""
        
        if config.framework == "shadcn":
            return self._setup_shadcn(config)
        elif config.framework == "antd":
            return self._setup_antd(config)
        elif config.framework == "mui":
            return self._setup_mui(config)
        elif config.framework == "bootstrap":
            return self._setup_bootstrap(config)
        elif config.framework == "chakra":
            return self._setup_chakra(config)
        elif config.framework == "tailwind":
            return self._setup_tailwind(config)
        elif config.framework == "daisy":
            return self._setup_daisy(config)
        else:
            raise ValueError(f"Unsupported framework: {config.framework}")
    
    # ============== SHADCN/UI (Tailwind + Radix) ==============
    
    def _setup_shadcn(self, config: UIFrameworkConfig) -> Dict[str, str]:
        """Setup Shadcn/ui - headless component library"""
        files = {}
        
        files["components.json"] = self._template_shadcn_components_json(config)
        files["package.json"] = self._template_shadcn_package_json()
        files["lib/utils.ts"] = self._template_shadcn_utils()
        files["components/ui/button.tsx"] = self._template_shadcn_button()
        files["components/ui/card.tsx"] = self._template_shadcn_card()
        files["components/ui/input.tsx"] = self._template_shadcn_input()
        files["components/ui/label.tsx"] = self._template_shadcn_label()
        files["components/ui/select.tsx"] = self._template_shadcn_select()
        files["components/ui/dropdown-menu.tsx"] = self._template_shadcn_dropdown()
        files["components/ui/dialog.tsx"] = self._template_shadcn_dialog()
        files["components/ui/sheet.tsx"] = self._template_shadcn_sheet()
        files["components/ui/toast.tsx"] = self._template_shadcn_toast()
        files["components/ui/tabs.tsx"] = self._template_shadcn_tabs()
        files["components/ui/badge.tsx"] = self._template_shadcn_badge()
        files["components/ui/separator.tsx"] = self._template_shadcn_separator()
        files["tailwind.config.ts"] = self._template_shadcn_tailwind_config()
        files["theme.tsx"] = self._template_shadcn_theme_provider()
        
        return files
    
    def _template_shadcn_components_json(self, config: UIFrameworkConfig) -> str:
        return json.dumps({
            "$schema": "https://ui.shadcn.com/schema.json",
            "style": "new-york",
            "rsc": False,
            "tsx": True,
            "aliasPrefix": "@",
            "components": {
                "path": "src/components/ui",
                "globals": "src/index.css"
            }
        }, indent=2)
    
    def _template_shadcn_package_json(self) -> str:
        return json.dumps({
            "dependencies": {
                "@radix-ui/react-dialog": "^1.1.1",
                "@radix-ui/react-dropdown-menu": "^2.0.6",
                "@radix-ui/react-label": "^2.0.2",
                "@radix-ui/react-select": "^2.0.0",
                "@radix-ui/react-sheet": "^1.0.3",
                "@radix-ui/react-tabs": "^1.0.4",
                "@radix-ui/react-toast": "^1.1.5",
                "class-variance-authority": "^0.7.0",
                "clsx": "^2.0.0",
                "tailwind-merge": "^2.2.0",
                "tailwindcss-animate": "^1.0.7"
            },
            "devDependencies": {
                "tailwindcss": "^3.3.6"
            }
        }, indent=2)
    
    def _template_shadcn_utils(self) -> str:
        return """import { clsx, type ClassValue } from "clsx"
import { twMerge } from "tailwind-merge"

export function cn(...inputs: ClassValue[]) {
  return twMerge(clsx(inputs))
}
"""
    
    def _template_shadcn_button(self) -> str:
        return """import * as React from "react"
import { Slot } from "@radix-ui/react-slot"
import { cva, type VariantProps } from "class-variance-authority"
import { cn } from "@/lib/utils"

const buttonVariants = cva(
  "inline-flex items-center justify-center whitespace-nowrap rounded-md text-sm font-medium ring-offset-background transition-colors focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring focus-visible:ring-offset-2 disabled:pointer-events-none disabled:opacity-50",
  {
    variants: {
      variant: {
        default: "bg-primary text-primary-foreground hover:bg-primary/90",
        destructive: "bg-destructive text-destructive-foreground hover:bg-destructive/90",
        outline: "border border-input bg-background hover:bg-accent hover:text-accent-foreground",
        secondary: "bg-secondary text-secondary-foreground hover:bg-secondary/80",
        ghost: "hover:bg-accent hover:text-accent-foreground",
        link: "text-primary underline-offset-4 hover:underline",
      },
      size: {
        default: "h-10 px-4 py-2",
        sm: "h-9 rounded-md px-3",
        lg: "h-11 rounded-md px-8",
        icon: "h-10 w-10",
      },
    },
    defaultVariants: {
      variant: "default",
      size: "default",
    },
  }
)

export interface ButtonProps
  extends React.ButtonHTMLAttributes<HTMLButtonElement>,
    VariantProps<typeof buttonVariants> {
  asChild?: boolean
}

const Button = React.forwardRef<HTMLButtonElement, ButtonProps>(
  ({ className, variant, size, asChild = false, ...props }, ref) => {
    const Comp = asChild ? Slot : "button"
    return (
      <Comp
        className={cn(buttonVariants({ variant, size, className }))}
        ref={ref}
        {...props}
      />
    )
  }
)
Button.displayName = "Button"

export { Button, buttonVariants }
"""
    
